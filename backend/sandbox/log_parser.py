"""Parses Maven Surefire test XML reports and compiler STDOUT logs."""

import re
from pathlib import Path
from typing import Dict, Any, Optional
import xml.etree.ElementTree as ET
from pydantic import BaseModel


class TestExecutionSummary(BaseModel):
    total: int = 0
    passed: int = 0
    failed: int = 0
    errors: int = 0
    skipped: int = 0


class LogDiagnosticParser:
    """Extracts test counts and compiler errors from sandbox output."""

    @classmethod
    def parse_surefire_reports(cls, workspace_root: Path) -> TestExecutionSummary:
        """Parses all TEST-*.xml files generated by Maven Surefire plugin."""
        total = passed = failed = errors = skipped = 0

        for xml_path in workspace_root.glob("**/target/surefire-reports/TEST-*.xml"):
            try:
                tree = ET.parse(str(xml_path))
                root = tree.getroot()
                t = int(root.attrib.get("tests", 0))
                f = int(root.attrib.get("failures", 0))
                e = int(root.attrib.get("errors", 0))
                s = int(root.attrib.get("skipped", 0))
                
                total += t
                failed += f
                errors += e
                skipped += s
                passed += (t - f - e - s)
            except Exception:
                pass

        return TestExecutionSummary(
            total=total,
            passed=passed,
            failed=failed,
            errors=errors,
            skipped=skipped,
        )

    @classmethod
    def extract_compiler_errors(cls, log_output: str) -> str:
        """Filters out verbose Maven download noise, isolating only compilation errors."""
        error_lines = []
        capture = False

        for line in log_output.splitlines():
            if "[ERROR] COMPILATION ERROR :" in line or "[ERROR] /" in line or "[ERROR] Failed to execute goal" in line:
                capture = True
            if capture:
                error_lines.append(line)
                if len(error_lines) > 50:  # Cap length for LLM diagnosis
                    break

        return "\n".join(error_lines) if error_lines else log_output[-1000:]
