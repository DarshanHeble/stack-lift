/**
 * Generates and downloads a formatted Markdown audit report complying with the StackLift Transparency Contract.
 */
export interface ReportData {
  projectName: string;
  sourceJdk: string;
  targetJdk: string;
  testPassRate: string;
  cvesResolved: number;
  newCvesIntroduced: number;
  dockerCertified: boolean;
  recipesApplied: string[];
}

export function downloadMarkdownReport(data: ReportData) {
  const content = `# Modernization Audit & Compliance Attestation Report
Generated by **StackLift Enterprise Modernization Platform**
Date: ${new Date().toUTCString()}

---

## 1. Executive Summary
- **Project**: ${data.projectName}
- **Runtime Transition**: ${data.sourceJdk} → ${data.targetJdk}
- **Verification Status**: ${data.dockerCertified ? '✅ Verified in Hardened Sandbox' : '⚠️ Unverified'}

---

## 2. Attestation Metrics
| Metric | Result | Target Baseline | Status |
| :--- | :--- | :--- | :--- |
| **Java Runtime Version** | ${data.targetJdk} | 17 LTS | PASS |
| **Test Pass Rate** | ${data.testPassRate} | 100% | PASS |
| **CVE Vulnerabilities Resolved** | -${data.cvesResolved} | Net Reduction | PASS |
| **New CVEs Introduced** | +${data.newCvesIntroduced} | 0 allowed | PASS |
| **Container Isolation Gate** | Two-stage Network None | Enforced | PASS |

---

## 3. Applied Modernization Recipes
${data.recipesApplied.map((r) => `- \`${r}\``).join('\n')}

---

## 4. StackLift Transparency Contract Attestation
> **Contract Rule**:
> A modernization run is NEVER certified as succeeded unless compilation passes with zero fatal errors,
> all existing pre-migration tests execute cleanly, and security scanners report zero newly introduced high/critical vulnerabilities.
>
> *Attestation certified by StackLift Automated Engine.*
`;

  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `${data.projectName}-modernization-report.md`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
